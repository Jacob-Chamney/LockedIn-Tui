import type { Rgba } from "./raster"

const FALLBACK = FONT8["?".charCodeAt(0) - 32]!

/** Width in pixels of one line, including the font's blank right column. */
export function pixelTextWidth(text: string, scale = 1): number {
  return Array.from(text).length * 8 * scale
}

/**
 * Draw one line into an RGBA frame at a fractional pixel position.
 *
 * Each font pixel is a small rectangle; destination pixels receive the
 * rectangle's overlap as alpha coverage. A half-pixel move therefore changes
 * the edge alpha instead of jumping a whole pixel, which is what makes the
 * label drift smoothly with its node.
 */
export function drawPixelText(
  buffer: Uint8Array,
  width: number,
  height: number,
  x: number,
  y: number,
  text: string,
  colour: Rgba,
  scale = 1,
  scaleY = scale,
): void {
  const paint = (px: number, py: number, coverage: number): void => {
    if (coverage <= 0 || px < 0 || py < 0 || px >= width || py >= height) return
    const alpha = (colour.a / 255) * Math.min(1, coverage)
    if (alpha <= 0) return
    const at = (py * width + px) * 4
    const inverse = 1 - alpha
    buffer[at] = Math.round(colour.r * alpha + (buffer[at] ?? 0) * inverse)
    buffer[at + 1] = Math.round(colour.g * alpha + (buffer[at + 1] ?? 0) * inverse)
    buffer[at + 2] = Math.round(colour.b * alpha + (buffer[at + 2] ?? 0) * inverse)
    buffer[at + 3] = 255
  }

  const characters = Array.from(text)
  for (let index = 0; index < characters.length; index++) {
    const character = characters[index]!
    const code = character.charCodeAt(0)
    const glyph = code >= 32 && code <= 126 ? FONT8[code - 32] ?? FALLBACK : FALLBACK
    const glyphX = x + index * 8 * scale
    for (let row = 0; row < 8; row++) {
      const bits = glyph[row] ?? 0
      for (let column = 0; column < 8; column++) {
        if ((bits & (1 << column)) === 0) continue
        const left = glyphX + column * scale
        const top = y + row * scaleY
        const right = left + scale
        const bottom = top + scaleY
        const fromX = Math.floor(left)
        const toX = Math.ceil(right) - 1
        const fromY = Math.floor(top)
        const toY = Math.ceil(bottom) - 1
        for (let py = fromY; py <= toY; py++) {
          const coverY = Math.max(0, Math.min(bottom, py + 1) - Math.max(top, py))
          if (coverY <= 0) continue
          for (let px = fromX; px <= toX; px++) {
            const coverX = Math.max(0, Math.min(right, px + 1) - Math.max(left, px))
            if (coverX <= 0) continue
            paint(px, py, coverX * coverY)
          }
        }
      }
    }
  }
}
